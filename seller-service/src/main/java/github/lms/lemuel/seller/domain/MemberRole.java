package github.lms.lemuel.seller.domain;

/**
 * 셀러 조직 안에서의 역할.
 *
 * <p><b>파트너 콘솔과 달리 여기서는 역할이 실제로 권한을 가른다.</b> 파트너 쪽 API 는 전부
 * 읽기라 조직에 속한 사람이면 같은 것을 봤지만, 여기에는 쓰기가 있다 — 상품 등록 신청과
 * 송장 등록이다. 둘 다 밖으로 나가는 결과가 있다: 신청은 승인되면 카탈로그에 상품이 실리고,
 * 송장은 구매자에게 "발송됨" 으로 보인다.
 *
 * <p>그래서 경계를 하나만 둔다 — <b>제출(submit)은 STAFF 가 할 수 없다.</b> 작성·수정까지는
 * 누구나 하고, 밖으로 내보내는 순간에만 책임자가 필요하다. 이 한 줄이 레퍼런스
 * (ssgb2e-outbackoffice)에 없던 것이다. 거기서는 로그인만 하면 전원이 같은 권한이었다.
 *
 * <p>경계를 더 잘게 나누지 않은 이유는 나눌 근거가 없어서다. 지금 있는 사실은 "역할 세 개" 뿐이고,
 * 그 위에 그럴듯한 권한 표를 만들면 검증되지 않은 통제가 검증된 것처럼 보인다.
 */
public enum MemberRole {

    OWNER,
    MANAGER,
    STAFF;

    /**
     * 신청서를 심사에 올리거나 송장을 등록할 수 있는가.
     *
     * <p>STAFF 는 초안까지만 만든다. 제출 버튼을 화면에서 감추는 것으로는 부족하다 —
     * API 는 화면 없이도 호출되기 때문에 서버에서 같은 판단을 한 번 더 한다.
     */
    public boolean canSubmit() {
        return this != STAFF;
    }
}
