-- V4 : board_attachments.thumbnail_path — 목록용 축소본 (board 스키마 — V1 주석 참조)
--
-- 갤러리 목록이 원본 이미지를 CSS 로 줄여 그리고 있었다. 5MB 사진 20장이 걸린 한 페이지는
-- 100MB 를 내려받는다 — 화면은 멀쩡해 보이므로 트래픽 청구서로만 드러나는 종류의 낭비다.
--
-- NULL 을 허용한다. WEBP 은 JDK ImageIO 에 리더가 없어 축소본을 만들 수 없고, 손상된 이미지도
-- 마찬가지다. 그때 업로드를 실패시키면 부가 기능이 본 기능을 죽이는 셈이라, 축소본 없이 저장하고
-- 조회 시 원본으로 떨어뜨린다.
-- ============================================================

ALTER TABLE board.board_attachments ADD COLUMN IF NOT EXISTS thumbnail_path VARCHAR(300);
