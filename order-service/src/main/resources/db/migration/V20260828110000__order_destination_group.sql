-- ============================================================
-- V20260828110000 : 여러 곳 배송 — 한 번의 결제로 만들어진 주문들을 묶는 표식
--
-- 여러 곳 배송은 주문 하나를 N 곳으로 쪼개지 않는다. 배송지마다 주문을 하나씩 만든다.
-- 배송(shipment)이 주문과 1:1 이라는 기존 불변식을 그대로 두기 위해서다 — 그 자리를
-- 1:N 으로 바꾸면 운송장 일괄 등록·배송 지연 스캐너·반품 회수까지 "주문의 배송" 이라는
-- 전제 위에 서 있는 코드가 전부 흔들린다.
--
-- 대신 흩어진 주문들이 한 번의 결제에서 나왔다는 사실을 잃지 않아야 한다. 그 표식이 이
-- 컬럼이다. 없으면 사용자는 주문 목록에서 갑자기 늘어난 세 건을 보고 자기가 세 번 결제한
-- 줄 알고, 멱등 재요청은 N 건 중 1 건만 돌려주게 된다(멱등 원장은 키 하나에 주문 id
-- 하나만 담는다).
--
-- nullable 이다. 여러 곳 배송이 아닌 주문 — 지금까지의 모든 주문 — 은 그냥 비어 있다.
-- 기본값을 두거나 NOT NULL 로 만들면 "묶음이 아니다" 를 표현할 수 없다.
--
-- 인덱스는 부분 인덱스다. 값이 있는 행이 전체 주문의 극히 일부라 NULL 까지 담을 이유가
-- 없고, 이 컬럼으로 하는 조회는 언제나 "이 그룹의 주문들" 하나뿐이다.
-- ============================================================

ALTER TABLE opslab.orders
    ADD COLUMN IF NOT EXISTS destination_group_id VARCHAR(36);

COMMENT ON COLUMN opslab.orders.destination_group_id IS
    '여러 곳 배송 묶음 id (UUID). 한 번의 결제에서 나온 주문들이 같은 값을 갖는다. 단일 배송지 주문은 NULL';

CREATE INDEX IF NOT EXISTS ix_orders_destination_group
    ON opslab.orders (destination_group_id, id)
    WHERE destination_group_id IS NOT NULL;
