package github.lms.lemuel.review.domain;

/**
 * 리뷰 노출 상태.
 *
 * <p><b>삭제가 아니라 블라인드인 이유</b>: 신고된 리뷰를 지워 버리면 "왜 사라졌는지"를 나중에
 * 설명할 수 없고, 오판이었을 때 되돌릴 것도 남지 않는다. 원문은 보존하고 <b>노출만</b> 끊는다 —
 * 그래야 이의 제기에 답할 수 있고 복구도 한 번의 조작으로 끝난다.
 *
 * <p>작성자 본인에게는 숨긴 리뷰도 보인다. 자기 글이 사라진 이유를 모르는 것이 가장 나쁜
 * 경험이고, 숨긴 사유를 보여 줄 수 있어야 이의 제기가 성립한다.
 */
public enum ReviewStatus {

    /** 공개 — 상품 상세의 리뷰 목록에 나온다. */
    VISIBLE,

    /** 블라인드 — 원문은 남지만 공개 목록에서 빠진다. */
    HIDDEN;

    public boolean isHidden() {
        return this == HIDDEN;
    }
}
