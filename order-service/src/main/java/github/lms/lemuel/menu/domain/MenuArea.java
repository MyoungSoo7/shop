package github.lms.lemuel.menu.domain;

/**
 * 메뉴 영역 — 하나의 셸(상단 네비 + 좌측 사이드바)이 담당하는 페르소나 묶음.
 *
 * <p>영역은 화면 셸과 1:1 이므로 코드(enum)로 봉인한다. 영역을 늘리는 일은 데이터 입력이 아니라
 * 프론트 셸을 새로 만드는 일이고, 시드 SQL 이 임의 문자열을 넣어 렌더링되지 않는 메뉴를 만드는
 * 사고를 막아야 하기 때문이다.
 */
public enum MenuArea {
    /** 구매자 — 주문·추천·장바구니 */
    SHOP,
    /** 셀러 셀프서비스 — 내 정산·세금계산서·예치금 */
    SELLER,
    /** 정산운영 백오피스 — 정산·대사·원장·지급 */
    BACKOFFICE,
    /** 법인 재무 — 조직·법인카드·지출 */
    CORP,
    /** 대표 — 인사이트·투자·대출·계정계 */
    CEO,
    /** 시스템 관리 — 메뉴·코드·RBAC·관제 */
    SYSTEM
}
