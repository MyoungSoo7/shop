package github.lms.lemuel.shipping.domain;

/**
 * 배송 추적 이벤트의 출처.
 *
 * <p>둘을 <b>구분해서</b> 보관하는 이유는 신뢰도가 다르기 때문이다. {@link #INTERNAL} 은 우리
 * 시스템이 직접 일으킨 상태 전이라 언제나 사실이고 되짚을 수 있다. {@link #CARRIER} 는 택배사가
 * 알려준 스캔 기록이라 지연·누락·정정이 있을 수 있고, 조회 자체가 실패할 수도 있다.
 *
 * <p>그래서 화면은 출처를 함께 보여준다. 섞어 놓으면 택배사 조회가 실패했을 때 "배송이 멈췄다"와
 * "택배사 정보를 못 불러왔다"를 사용자가 구분할 수 없다.
 */
public enum TrackingEventSource {
    /** 우리 시스템의 상태 전이(출고 처리, 배송 완료 처리 등). 저장된다. */
    INTERNAL,
    /** 택배사 스캔 기록. 조회 시점에 가져오며 저장하지 않는다. */
    CARRIER
}
