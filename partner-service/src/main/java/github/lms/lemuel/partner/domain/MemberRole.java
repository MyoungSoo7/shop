package github.lms.lemuel.partner.domain;

/**
 * 파트너 조직 안에서의 역할.
 *
 * <p><b>이 서비스에서 역할은 아직 권한을 가르지 않는다.</b> 여기 있는 모든 API 는 읽기 전용이고,
 * 조직에 속한 사람이면 같은 것을 본다. 그래서 세 값의 차이는 화면 표시뿐이다.
 *
 * <p>그럼에도 값을 그대로 들고 오는 이유는, 없는 걸 만들어 채우는 것보다 원본을 보존하는 편이
 * 나중에 역할별 통제를 넣을 때 정확하기 때문이다. 다만 지금 없는 통제를 있는 척하지는 않는다 —
 * "STAFF 는 매출을 못 본다" 같은 규칙을 넣고 싶으면 그때 실제로 검사를 추가해야 한다.
 */
public enum MemberRole {
    OWNER,
    MANAGER,
    STAFF
}
